 float Egg::moduloRotationsAsPositive(float rotation_rad)
 {
    float moduloRotations = rotation_rad - ( (2 * PI_F) * ( static_cast<int>(rotation_rad/(2*PI_F)) ) );
     
    return (moduloRotations < 0) ? ((2*PI_F) + moduloRotations) : (moduloRotations);
 }


